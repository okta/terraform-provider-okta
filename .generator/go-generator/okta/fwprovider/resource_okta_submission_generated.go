func (r *submissionResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan submissionModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state submissionModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	id := state.ID.ValueString()

	client := r.Config.OktaIDaaSClient.OktaSDKClient()

	// Build request body from plan — only send changed fields
	updateReq := client.YourOinIntegrationsAPI.ReplaceSubmission(ctx, id)
	updateBody := okta.NewSubmissionRequestWithDefaults()
	if len(plan.AppContactDetails) > 0 {
		var appContactDetailsSlice []okta.SubmissionRequestAppContactDetailsInner
		for _, item := range plan.AppContactDetails {
			nestedItem := okta.NewSubmissionRequestAppContactDetailsInnerWithDefaults()
			if !item.Contact.IsNull() && !item.Contact.IsUnknown() {
				nestedItem.SetContact(item.Contact.ValueString())
			}
			if !item.ContactType.IsNull() && !item.ContactType.IsUnknown() {
				nestedItem.SetContactType(item.ContactType.ValueString())
			}
			if !item.ContactValueType.IsNull() && !item.ContactValueType.IsUnknown() {
				nestedItem.SetContactValueType(item.ContactValueType.ValueString())
			}
			appContactDetailsSlice = append(appContactDetailsSlice, *nestedItem)
		}
		updateBody.SetAppContactDetails(appContactDetailsSlice)
	}
	if plan.AuthSettings != nil {
		nestedAuthSettings := okta.NewAuthSettingsWithDefaults()
		if !plan.AuthSettings.AuthType.IsNull() && !plan.AuthSettings.AuthType.IsUnknown() {
			nestedAuthSettings.SetAuthType(plan.AuthSettings.AuthType.ValueString())
		}
		updateBody.SetAuthSettings(*nestedAuthSettings)
	}
	if !plan.Capabilities.IsNull() && !plan.Capabilities.IsUnknown() {
		var capabilitiesSlice []string
		for _, item := range plan.Capabilities.Elements() {
			if sv, ok := item.(types.String); ok {
				capabilitiesSlice = append(capabilitiesSlice, sv.ValueString())
			}
		}
		updateBody.SetCapabilities(capabilitiesSlice)
	}
	if len(plan.Config) > 0 {
		var configSlice []okta.SubmissionRequestConfigInner
		for _, item := range plan.Config {
			nestedItem := okta.NewSubmissionRequestConfigInnerWithDefaults()
			if !item.Label.IsNull() && !item.Label.IsUnknown() {
				nestedItem.SetLabel(item.Label.ValueString())
			}
			if !item.Name.IsNull() && !item.Name.IsUnknown() {
				nestedItem.SetName(item.Name.ValueString())
			}
			configSlice = append(configSlice, *nestedItem)
		}
		updateBody.SetConfig(configSlice)
	}
	updateBody.SetDefaultLogo(plan.DefaultLogo.ValueBool())
	updateBody.SetDescription(plan.Description.ValueString())
	if plan.GlobalTokenRevocation != nil {
		nestedGlobalTokenRevocation := okta.NewGlobalTokenRevocationWithDefaults()
		if !plan.GlobalTokenRevocation.AuthMethod.IsNull() && !plan.GlobalTokenRevocation.AuthMethod.IsUnknown() {
			nestedGlobalTokenRevocation.SetAuthMethod(plan.GlobalTokenRevocation.AuthMethod.ValueString())
		}
		if !plan.GlobalTokenRevocation.Endpoint.IsNull() && !plan.GlobalTokenRevocation.Endpoint.IsUnknown() {
			nestedGlobalTokenRevocation.SetEndpoint(plan.GlobalTokenRevocation.Endpoint.ValueString())
		}
		if !plan.GlobalTokenRevocation.PartialLogout.IsNull() && !plan.GlobalTokenRevocation.PartialLogout.IsUnknown() {
			nestedGlobalTokenRevocation.SetPartialLogout(plan.GlobalTokenRevocation.PartialLogout.ValueBool())
		}
		if !plan.GlobalTokenRevocation.SubjectFormat.IsNull() && !plan.GlobalTokenRevocation.SubjectFormat.IsUnknown() {
			nestedGlobalTokenRevocation.SetSubjectFormat(plan.GlobalTokenRevocation.SubjectFormat.ValueString())
		}
		updateBody.SetGlobalTokenRevocation(*nestedGlobalTokenRevocation)
	}
	updateBody.SetLogo(plan.Logo.ValueString())
	updateBody.SetName(plan.Name.ValueString())
	if plan.Provisioning != nil {
		nestedProvisioning := okta.NewProvisioningDetailsWithDefaults()
		if !plan.Provisioning.Features.IsNull() && !plan.Provisioning.Features.IsUnknown() {
			var featuresSlice []string
			for _, elem := range plan.Provisioning.Features.Elements() {
				if sv, ok := elem.(types.String); ok {
					featuresSlice = append(featuresSlice, sv.ValueString())
				}
			}
			nestedProvisioning.SetFeatures(featuresSlice)
		}
		updateBody.SetProvisioning(*nestedProvisioning)
	}
	if plan.Sso != nil {
		nestedSso := okta.NewSsoWithDefaults()
		updateBody.SetSso(*nestedSso)
	}
	if !plan.UseCases.IsNull() && !plan.UseCases.IsUnknown() {
		var useCasesSlice []string
		for _, item := range plan.UseCases.Elements() {
			if sv, ok := item.(types.String); ok {
				useCasesSlice = append(useCasesSlice, sv.ValueString())
			}
		}
		updateBody.SetUseCases(useCasesSlice)
	}
	updateReq = updateReq.SubmissionRequest(*updateBody)
	result, _, err := updateReq.Execute()
	if err != nil {
		resp.Diagnostics.AddError("Error updating submission", err.Error())
		return
	}
	// Map API response fields to state (scalar types only; WriteOnly and SkipRead fields skipped)
	state.ID = types.StringValue(string(result.GetId()))
	state.CaseLastUpdated = types.StringValue(string(result.GetCaseLastUpdated()))
	state.DefaultLogo = types.BoolValue(result.GetDefaultLogo())
	if v := result.GetDescription(); v != "" {
		state.Description = types.StringValue(string(v))
	} else {
		state.Description = types.StringNull()
	}
	state.IsNonFunctionalOnlySubmission = types.BoolValue(result.GetIsNonFunctionalOnlySubmission())
	state.LastPublished = types.StringValue(string(result.GetLastPublished()))
	state.LastUpdated = types.StringValue(string(result.GetLastUpdated()))
	state.LastUpdatedBy = types.StringValue(string(result.GetLastUpdatedBy()))
	if v := result.GetLogo(); v != "" {
		state.Logo = types.StringValue(string(v))
	} else {
		state.Logo = types.StringNull()
	}
	if v := result.GetName(); v != "" {
		state.Name = types.StringValue(string(v))
	} else {
		state.Name = types.StringNull()
	}
	state.OinFeatures = types.StringValue(string(result.GetOinFeatures()))
	state.Status = types.StringValue(string(result.GetStatus()))

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

